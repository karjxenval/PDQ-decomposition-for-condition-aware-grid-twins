def safe_mkdir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def set_seed(seed: int) -> np.random.Generator:
    return np.random.default_rng(seed)


def http_get_json(url: str, params: Dict[str, Any], user_agent: str, timeout: int = 90) -> Any:
    headers = {"User-Agent": user_agent}
    r = requests.get(url, params=params, headers=headers, timeout=timeout)
    r.raise_for_status()
    return r.json()


def http_post_text(url: str, data: str, user_agent: str, timeout: int = 180) -> Any:
    headers = {"User-Agent": user_agent}
    r = requests.post(url, data={"data": data}, headers=headers, timeout=timeout)
    r.raise_for_status()
    return r.json()


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    radius = 6371.0088
    p1 = math.radians(lat1)
    p2 = math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * radius * math.asin(math.sqrt(a))


def relative_noise(x: np.ndarray, level: float, rng: np.random.Generator) -> np.ndarray:
    if level <= 0:
        return np.zeros_like(x)
    eta = rng.standard_normal(size=x.shape)
    eta_norm = np.linalg.norm(eta)
    x_norm = max(np.linalg.norm(x), 1e-14)
    if eta_norm < 1e-14:
        return np.zeros_like(x)
    return eta / eta_norm * (level * x_norm)


def condition_number_from_svals(svals: np.ndarray, eps: float = 1e-14) -> float:
    if len(svals) == 0:
        return float("inf")
    smax = float(np.max(svals))
    smin = float(np.min(svals))
    if smin <= eps:
        return float("inf")
    return smax / smin


def finite_or_nan(x: float) -> float:
    return float(x) if np.isfinite(x) else np.nan


