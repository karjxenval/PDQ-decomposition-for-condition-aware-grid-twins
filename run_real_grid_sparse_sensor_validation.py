def aggregate(df: pd.DataFrame, group_cols: List[str]) -> pd.DataFrame:
    cols = [
        "RelErr",
        "MaxErr",
        "EnergyErr",
        "BasisErr",
        "sigma_min_SB",
        "kappa_SB",
        "amplification",
        "online_time_sec",
        "fit_time_sec",
        "gamma",
        "n_sensors_used",
    ]
    out = df.groupby(group_cols)[cols].agg(["mean", "std", "median"]).reset_index()
    out.columns = [
        "_".join([str(x) for x in c if str(x) != ""]).rstrip("_")
        for c in out.columns
    ]
    return out


def save_tables_and_figures(
    df: pd.DataFrame,
    G: nx.Graph,
    nodes_df: pd.DataFrame,
    edges_df: pd.DataFrame,
    weather: pd.DataFrame,
    tables_dir: Path,
    figures_dir: Path,
) -> None:
    raw_specs = {
        "table_sensor_budget.csv": (df[df["experiment"] == "sensor_budget"], ["experiment", "method", "sensor_budget"]),
        "table_noise.csv": (df[df["experiment"] == "noise"], ["experiment", "method", "noise_level"]),
        "table_placement.csv": (df[df["experiment"] == "placement"], ["experiment", "method", "placement"]),
    }

    for name, (sub, group_cols) in raw_specs.items():
        aggregate(sub, group_cols).to_csv(tables_dir / name, index=False)

    summary = df.groupby(["experiment", "method"]).agg(
        RelErr_mean=("RelErr", "mean"),
        EnergyErr_mean=("EnergyErr", "mean"),
        kappa_SB_median=("kappa_SB", "median"),
        amplification_median=("amplification", "median"),
        online_time_mean=("online_time_sec", "mean"),
    ).reset_index()
    summary.to_csv(tables_dir / "summary_key_results.csv", index=False)

    plot_grid(G, nodes_df, edges_df, figures_dir / "real_grid_map.png")
    plot_weather(weather, figures_dir / "real_grid_weather.png")

    table_budget = pd.read_csv(tables_dir / "table_sensor_budget.csv")
    plot_lines(table_budget, "sensor_budget", "RelErr_mean", "method",
               "Sensor budget s/n", "Mean relative recovery error",
               "Real-grid recovery versus sensor budget",
               figures_dir / "fig_sensor_budget_relerr.png")

    table_noise = pd.read_csv(tables_dir / "table_noise.csv")
    plot_lines(table_noise, "noise_level", "RelErr_mean", "method",
               "Relative sensor noise", "Mean relative recovery error",
               "Real-grid noise robustness",
               figures_dir / "fig_noise_relerr.png")

    table_place = pd.read_csv(tables_dir / "table_placement.csv")
    plot_placement(table_place, figures_dir / "fig_placement_relerr.png")

    plot_condition_vs_error(df, figures_dir / "fig_condition_vs_error.png")


def plot_grid(G: nx.Graph, nodes_df: pd.DataFrame, edges_df: pd.DataFrame, outpath: Path) -> None:
    pos = {int(r.node): (float(r.lon), float(r.lat)) for r in nodes_df.itertuples()}
    plt.figure(figsize=(7.2, 7.2))
    for u, v in G.edges():
        x1, y1 = pos[u]
        x2, y2 = pos[v]
        plt.plot([x1, x2], [y1, y2], linewidth=0.7, alpha=0.65)
    deg = nodes_df["degree"].to_numpy()
    plt.scatter(nodes_df["lon"], nodes_df["lat"], s=8 + 6 * deg, alpha=0.85)
    plt.xlabel("Longitude")
    plt.ylabel("Latitude")
    plt.title("Real OpenStreetMap power-grid topology used for validation")
    plt.grid(True, alpha=0.25)
    plt.tight_layout()
    plt.savefig(outpath, dpi=300)
    plt.close()


def plot_weather(weather: pd.DataFrame, outpath: Path) -> None:
    df = weather.copy()
    df["time"] = pd.to_datetime(df["time"])
    plt.figure(figsize=(8.4, 4.6))
    plt.plot(df["time"], df["temperature_2m"], label="Temperature 2m")
    if "shortwave_radiation" in df:
        rad = df["shortwave_radiation"].to_numpy(dtype=float)
        rad_scaled = (rad - np.nanmin(rad)) / (np.nanmax(rad) - np.nanmin(rad) + 1e-12)
        temp = df["temperature_2m"].to_numpy(dtype=float)
        rad_scaled = rad_scaled * (np.nanmax(temp) - np.nanmin(temp)) + np.nanmin(temp)
        plt.plot(df["time"], rad_scaled, label="Shortwave radiation, scaled")
    plt.xlabel("Time")
    plt.ylabel("Weather signal")
    plt.title("Downloaded real weather used as operational driver")
    plt.legend(frameon=False)
    plt.grid(True, alpha=0.25)
    plt.tight_layout()
    plt.savefig(outpath, dpi=300)
    plt.close()


def plot_lines(table: pd.DataFrame, x_col: str, y_col: str, group_col: str, xlabel: str, ylabel: str, title: str, outpath: Path) -> None:
    plt.figure(figsize=(7.2, 4.6))
    for method, sub in table.groupby(group_col):
        sub = sub.sort_values(x_col)
        plt.plot(sub[x_col], sub[y_col], marker="o", label=str(method))
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    plt.grid(True, alpha=0.3)
    plt.legend(frameon=False)
    plt.tight_layout()
    plt.savefig(outpath, dpi=300)
    plt.close()


def plot_placement(table: pd.DataFrame, outpath: Path) -> None:
    pivot = table.pivot_table(index="placement", columns="method", values="RelErr_mean", aggfunc="mean")
    plt.figure(figsize=(8.2, 4.8))
    pivot.plot(kind="bar", ax=plt.gca())
    plt.ylabel("Mean relative recovery error")
    plt.xlabel("Placement strategy")
    plt.title("Real-grid sensor placement effects")
    plt.grid(True, axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(outpath, dpi=300)
    plt.close()


def plot_condition_vs_error(df: pd.DataFrame, outpath: Path) -> None:
    sub = df.replace([np.inf, -np.inf], np.nan).dropna(subset=["kappa_SB", "RelErr"])
    if len(sub) > 3000:
        sub = sub.sample(3000, random_state=123)

    plt.figure(figsize=(7.2, 4.8))
    for method, part in sub.groupby("method"):
        plt.scatter(part["kappa_SB"], part["RelErr"], s=10, alpha=0.45, label=str(method))
    plt.xscale("log")
    plt.yscale("log")
    plt.xlabel(r"Sensed-basis condition number $\kappa(SB)$")
    plt.ylabel("Relative recovery error")
    plt.title("Conditioning versus recovery error on real grid topology")
    plt.grid(True, alpha=0.3)
    plt.legend(frameon=False)
    plt.tight_layout()
    plt.savefig(outpath, dpi=300)
    plt.close()


