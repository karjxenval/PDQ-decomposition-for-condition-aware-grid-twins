def select_sensors(B: np.ndarray, s: int, mode: str, rng: np.random.Generator, nodes_df: pd.DataFrame) -> np.ndarray:
    n = B.shape[0]
    s = max(1, min(int(s), n))

    lev = np.sum(B ** 2, axis=1)
    degree = nodes_df["degree"].to_numpy(dtype=float)

    if mode == "random":
        return np.sort(rng.choice(n, size=s, replace=False))

    if mode == "leverage":
        return np.sort(np.argsort(lev)[::-1][:s])

    if mode == "poor":
        return np.sort(np.argsort(lev)[:s])

    if mode == "degree":
        score = degree + 0.05 * lev / (np.max(lev) + 1e-12)
        return np.sort(np.argsort(score)[::-1][:s])

    if mode == "qr":
        try:
            _, _, piv = qr(B.T, pivoting=True, mode="economic")
            return np.sort(piv[:s])
        except Exception:
            return np.sort(np.argsort(lev)[::-1][:s])

    raise ValueError(f"Unknown placement mode: {mode}")


def recover(B: np.ndarray, x: np.ndarray, idx: np.ndarray, gamma: float, noise_level: float, rng: np.random.Generator, ridge_eps: float = 1e-12) -> Tuple[np.ndarray, Dict[str, float]]:
    G = B[idx, :]
    y_clean = x[idx]
    eta = relative_noise(y_clean, noise_level, rng)
    y = y_clean + eta

    r = B.shape[1]
    H = G.T @ G + gamma * np.eye(r)
    b = G.T @ y

    t0 = time.perf_counter()
    try:
        if gamma > 0:
            zhat = np.linalg.solve(H, b)
        else:
            zhat, *_ = np.linalg.lstsq(G, y, rcond=None)
    except np.linalg.LinAlgError:
        zhat = np.linalg.pinv(H + ridge_eps * np.eye(r)) @ b
    online_time = time.perf_counter() - t0

    xhat = B @ zhat

    svals = np.linalg.svd(G, compute_uv=False)
    if len(svals) < r:
        sigma_min = 0.0
    else:
        sigma_min = float(np.min(svals))
    sigma_max = float(np.max(svals)) if len(svals) else 0.0

    svals_full = np.concatenate([svals, np.zeros(max(0, r - len(svals)))])
    kappa = condition_number_from_svals(svals_full)

    try:
        amp_mat = np.linalg.solve(H + ridge_eps * np.eye(r), G.T)
        amplification = float(np.linalg.norm(B, 2) * np.linalg.norm(amp_mat, 2))
    except Exception:
        amplification = np.nan

    return xhat, {
        "noise_norm": float(np.linalg.norm(eta)),
        "sigma_min_SB": finite_or_nan(sigma_min),
        "sigma_max_SB": finite_or_nan(sigma_max),
        "kappa_SB": finite_or_nan(kappa),
        "amplification": finite_or_nan(amplification),
        "online_time_sec": float(online_time),
        "n_sensors_used": int(len(idx)),
    }


def basis_error(B: np.ndarray, x: np.ndarray) -> float:
    try:
        z, *_ = np.linalg.lstsq(B, x, rcond=None)
        xp = B @ z
    except Exception:
        xp = B @ (np.linalg.pinv(B) @ x)
    return float(np.linalg.norm(x - xp) / max(np.linalg.norm(x), 1e-14))


def metrics(x: np.ndarray, xhat: np.ndarray, L: Optional[csr_matrix] = None) -> Dict[str, float]:
    d = xhat - x
    rel = np.linalg.norm(d) / max(np.linalg.norm(x), 1e-14)
    maxerr = np.max(np.abs(d))
    if L is not None:
        num = float(d.T @ (L @ d))
        den = float(x.T @ (L @ x))
        energy = math.sqrt(max(num, 0.0)) / max(math.sqrt(max(den, 0.0)), 1e-14)
    else:
        energy = np.nan
    return {"RelErr": float(rel), "MaxErr": float(maxerr), "EnergyErr": float(energy)}


def choose_gamma(B: np.ndarray, X_val: np.ndarray, idx: np.ndarray, noise_level: float, cfg: Config) -> float:
    G = B[idx, :]
    scale = float(np.trace(G.T @ G) / max(B.shape[1], 1))
    scale = max(scale, 1e-12)

    best_gamma = None
    best_score = np.inf

    local_rng = np.random.default_rng(777)
    for mult in cfg.gamma_multipliers:
        gamma = float(mult * scale)
        errs = []
        for j in range(X_val.shape[1]):
            x = X_val[:, j]
            xhat, _ = recover(B, x, idx, gamma, noise_level, local_rng, cfg.ridge_eps)
            errs.append(metrics(x, xhat)["RelErr"])
        score = float(np.mean(errs))
        if score < best_score:
            best_score = score
            best_gamma = gamma

    return float(best_gamma if best_gamma is not None else 1e-8)


