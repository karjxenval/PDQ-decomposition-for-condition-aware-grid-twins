def svd_basis(A: np.ndarray, r: int) -> np.ndarray:
    U, _, _ = np.linalg.svd(A, full_matrices=False)
    return U[:, :r]


def randomized_svd_basis(A: np.ndarray, r: int, rng: np.random.Generator, oversample: int = 8, n_iter: int = 1) -> np.ndarray:
    n, m = A.shape
    ell = min(r + oversample, min(n, m))
    Omega = rng.standard_normal(size=(m, ell))
    Y = A @ Omega
    for _ in range(n_iter):
        Y = A @ (A.T @ Y)
    Q, _ = np.linalg.qr(Y, mode="reduced")
    Bsmall = Q.T @ A
    Usmall, _, _ = np.linalg.svd(Bsmall, full_matrices=False)
    U = Q @ Usmall
    return U[:, :r]


def cur_column_basis(A: np.ndarray, r: int) -> np.ndarray:
    U, _, Vt = np.linalg.svd(A, full_matrices=False)
    rr = min(r, Vt.shape[0])
    lev = np.sum(Vt[:rr, :] ** 2, axis=0)
    chosen = np.argsort(lev)[::-1][:r]
    C = A[:, chosen]
    Q, R = np.linalg.qr(C, mode="reduced")
    if Q.shape[1] < r or np.linalg.matrix_rank(R) < min(R.shape):
        return U[:, :r]
    return Q[:, :r]


def pdq_condition_aware_basis(A: np.ndarray, r: int, kappa_max: float = 50.0, eps: float = 1e-12) -> Tuple[np.ndarray, Dict[str, float]]:
    U, s, _ = np.linalg.svd(A, full_matrices=False)
    U = U[:, :r]
    s = s[:r]
    smax = max(float(s[0]), eps)
    floor = smax / max(kappa_max, 1.0)
    d = np.sqrt(np.maximum(s, floor))
    B = U * d.reshape(1, -1)
    return B, {
        "pdq_core_kappa": float(np.max(d) / max(np.min(d), eps)),
        "pdq_core_min": float(np.min(d)),
        "pdq_core_max": float(np.max(d)),
    }


def fit_bases(A_train: np.ndarray, cfg: Config, rng: np.random.Generator) -> Dict[str, Dict[str, Any]]:
    bases: Dict[str, Dict[str, Any]] = {}

    t0 = time.perf_counter()
    bases["SVD"] = {"B": svd_basis(A_train, cfg.rank), "fit_time": time.perf_counter() - t0, "diagnostics": {}}

    t0 = time.perf_counter()
    bases["rSVD"] = {"B": randomized_svd_basis(A_train, cfg.rank, rng), "fit_time": time.perf_counter() - t0, "diagnostics": {}}

    t0 = time.perf_counter()
    bases["CUR"] = {"B": cur_column_basis(A_train, cfg.rank), "fit_time": time.perf_counter() - t0, "diagnostics": {}}

    t0 = time.perf_counter()
    Bpdq, diag = pdq_condition_aware_basis(A_train, cfg.rank, cfg.pdq_kappa_max)
    bases["PDQ"] = {"B": Bpdq, "fit_time": time.perf_counter() - t0, "diagnostics": diag}

    return bases


