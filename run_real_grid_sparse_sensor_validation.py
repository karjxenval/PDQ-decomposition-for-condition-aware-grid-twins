def download_weather(lat: float, lon: float, cfg: Config, out_csv: Path) -> pd.DataFrame:
    params = {
        "latitude": lat,
        "longitude": lon,
        "start_date": cfg.start_date,
        "end_date": cfg.end_date,
        "hourly": "temperature_2m,relative_humidity_2m,precipitation,wind_speed_10m,shortwave_radiation",
        "timezone": "auto",
    }

    data = http_get_json(cfg.open_meteo_url, params=params, user_agent=cfg.user_agent, timeout=90)

    hourly = data.get("hourly", {})
    if not hourly or "time" not in hourly:
        raise RuntimeError("Open-Meteo response did not contain hourly weather data.")

    df = pd.DataFrame(hourly)
    df.to_csv(out_csv, index=False)
    return df


def node_spatial_weights(nodes_df: pd.DataFrame, rng: np.random.Generator) -> np.ndarray:
    """
    Create fixed node-level demand weights from coordinates and degree.
    This is a transparent public-data proxy, not utility demand data.
    """
    lat = nodes_df["lat"].to_numpy(dtype=float)
    lon = nodes_df["lon"].to_numpy(dtype=float)
    degree = nodes_df["degree"].to_numpy(dtype=float)

    latn = (lat - np.nanmean(lat)) / (np.nanstd(lat) + 1e-12)
    lonn = (lon - np.nanmean(lon)) / (np.nanstd(lon) + 1e-12)

    base = 1.0 + 0.25 * degree + 0.15 * np.sin(2.0 * latn) + 0.15 * np.cos(2.0 * lonn)
    jitter = 0.08 * rng.standard_normal(size=len(base))
    w = np.maximum(base + jitter, 0.05)
    w = w / np.mean(w)
    return w


def generate_grid_response_snapshots(
    G: nx.Graph,
    nodes_df: pd.DataFrame,
    weather: pd.DataFrame,
    cfg: Config,
    rng: np.random.Generator,
) -> pd.DataFrame:
    """
    Generate operational response snapshots on the real OSM grid topology.

    Model:
      q_t = node injections influenced by real weather and hour-of-day.
      v_t solves (L + rho I) v = q_t with graph smoothing.
      response_t combines v_t with local normalized load.

    Interpretation:
      The topology and weather are real. The response is a transparent
      graph-physics surrogate for public validation when SCADA/full-field
      node measurements are unavailable.
    """
    n = G.number_of_nodes()
    L = graph_laplacian_conductance(G)

    rho = 0.08
    Aop = L + rho * diags(np.ones(n), 0, format="csr")

    w_node = node_spatial_weights(nodes_df, rng)

    df = weather.copy()
    df["time"] = pd.to_datetime(df["time"])
    hours = df["time"].dt.hour.to_numpy()

    temp = df["temperature_2m"].to_numpy(dtype=float)
    wind = df["wind_speed_10m"].to_numpy(dtype=float)
    rad = df["shortwave_radiation"].to_numpy(dtype=float)
    precip = df["precipitation"].to_numpy(dtype=float)

    temp_z = (temp - np.nanmean(temp)) / (np.nanstd(temp) + 1e-12)
    wind_z = (wind - np.nanmean(wind)) / (np.nanstd(wind) + 1e-12)
    rad_z = (rad - np.nanmean(rad)) / (np.nanstd(rad) + 1e-12)
    precip_z = (precip - np.nanmean(precip)) / (np.nanstd(precip) + 1e-12)

    # Demand-like daily profile
    daily = (
        1.0
        + 0.20 * np.sin(2 * np.pi * (hours - 7) / 24.0)
        + 0.15 * np.sin(2 * np.pi * (hours - 18) / 24.0)
    )

    # Weather-modulated demand and renewable-like stress terms
    system_driver = (
        daily
        + 0.12 * temp_z
        + 0.08 * wind_z
        - 0.10 * rad_z
        + 0.04 * precip_z
    )

    X = np.zeros((n, len(df)), dtype=float)

    for t in range(len(df)):
        spatial_wave = 0.05 * np.sin(0.2 * np.arange(n) + 0.1 * t)
        q = system_driver[t] * w_node + spatial_wave
        q = q - np.mean(q)
        q += 0.01 * rng.standard_normal(n)

        v = spsolve(Aop, q)
        v = np.asarray(v)
        v = (v - np.mean(v)) / (np.std(v) + 1e-12)

        # A public-data proxy response, analogous to normalized voltage/stress field.
        response = 0.75 * v + 0.25 * (q - np.mean(q)) / (np.std(q) + 1e-12)
        X[:, t] = response

    snap = pd.DataFrame(X, columns=[f"t_{i:04d}" for i in range(X.shape[1])])
    snap.insert(0, "node", np.arange(n))
    return snap


