def split_snapshots(X: np.ndarray, cfg: Config) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    m = X.shape[1]
    n_train = int(cfg.train_frac * m)
    n_val = int(cfg.val_frac * m)
    if n_train < 10 or n_val < 5 or m - n_train - n_val < 5:
        raise RuntimeError("Not enough weather/snapshot time points. Use a wider date range.")
    return X[:, :n_train], X[:, n_train:n_train + n_val], X[:, n_train + n_val:]


def evaluate(
    *,
    experiment: str,
    method: str,
    B: np.ndarray,
    fit_time: float,
    X_test: np.ndarray,
    X_val: np.ndarray,
    L: csr_matrix,
    nodes_df: pd.DataFrame,
    sensor_budget: float,
    noise_level: float,
    placement: str,
    cfg: Config,
    rng: np.random.Generator,
    trial: int,
) -> List[Dict[str, Any]]:
    n = B.shape[0]
    s = max(1, int(round(sensor_budget * n)))
    idx = select_sensors(B, s, placement, rng, nodes_df)
    gamma = choose_gamma(B, X_val, idx, noise_level, cfg)

    rows = []
    for j in range(X_test.shape[1]):
        x = X_test[:, j]
        xhat, diag = recover(B, x, idx, gamma, noise_level, rng, cfg.ridge_eps)
        row = {
            "experiment": experiment,
            "method": method,
            "sensor_budget": float(sensor_budget),
            "noise_level": float(noise_level),
            "placement": placement,
            "trial": int(trial),
            "snapshot_id": int(j),
            "gamma": float(gamma),
            "fit_time_sec": float(fit_time),
            "BasisErr": basis_error(B, x),
            **metrics(x, xhat, L),
            **diag,
        }
        rows.append(row)
    return rows


def run_validation(cfg: Config, outdir: Path) -> None:
    rng = set_seed(cfg.seed)

    data_dir = outdir / "data"
    tables_dir = outdir / "tables"
    figures_dir = outdir / "figures"
    for p in (data_dir, tables_dir, figures_dir):
        safe_mkdir(p)

    print("[1/7] Downloading real OSM power-grid infrastructure...")
    osm_payload = download_osm_power(cfg, data_dir / "osm_power_elements.json")

    print("[2/7] Building real grid graph...")
    G, nodes_df, edges_df = parse_osm_power_graph(osm_payload, cfg)
    nodes_df.to_csv(data_dir / "grid_nodes.csv", index=False)
    edges_df.to_csv(data_dir / "grid_edges.csv", index=False)

    centroid_lat = float(nodes_df["lat"].mean())
    centroid_lon = float(nodes_df["lon"].mean())

    print("[3/7] Downloading real historical weather...")
    weather = download_weather(centroid_lat, centroid_lon, cfg, data_dir / "weather_hourly.csv")

    print("[4/7] Generating topology-aware response snapshots on the real grid...")
    snapshots_df = generate_grid_response_snapshots(G, nodes_df, weather, cfg, rng)
    snapshots_df.to_csv(data_dir / "snapshots.csv", index=False)

    X = snapshots_df.drop(columns=["node"]).to_numpy(dtype=float)
    X_train, X_val, X_test = split_snapshots(X, cfg)

    # Remove temporal mean learned from train.
    mean_train = X_train.mean(axis=1, keepdims=True)
    X_train = X_train - mean_train
    X_val = X_val - mean_train
    X_test = X_test - mean_train

    L = graph_laplacian_conductance(G)

    print("[5/7] Fitting bases...")
    bases = fit_bases(X_train, cfg, rng)

    print("[6/7] Running real-data validation experiments...")
    rows: List[Dict[str, Any]] = []

    # Experiment 1: sensor budget
    for method, item in bases.items():
        for budget in cfg.sensor_budgets:
            for trial in range(cfg.n_trials):
                rows.extend(evaluate(
                    experiment="sensor_budget",
                    method=method,
                    B=item["B"],
                    fit_time=item["fit_time"],
                    X_test=X_test,
                    X_val=X_val,
                    L=L,
                    nodes_df=nodes_df,
                    sensor_budget=budget,
                    noise_level=0.05,
                    placement="qr",
                    cfg=cfg,
                    rng=np.random.default_rng(cfg.seed + 1000 + trial),
                    trial=trial,
                ))

    # Experiment 2: sensor noise
    for method, item in bases.items():
        for noise in cfg.noise_levels:
            rows.extend(evaluate(
                experiment="noise",
                method=method,
                B=item["B"],
                fit_time=item["fit_time"],
                X_test=X_test,
                X_val=X_val,
                L=L,
                nodes_df=nodes_df,
                sensor_budget=0.20,
                noise_level=noise,
                placement="qr",
                cfg=cfg,
                rng=np.random.default_rng(cfg.seed + 2000 + int(noise * 1000)),
                trial=0,
            ))

    # Experiment 3: sensor placement
    for method, item in bases.items():
        for placement in cfg.placement_modes:
            for trial in range(cfg.n_trials):
                rows.extend(evaluate(
                    experiment="placement",
                    method=method,
                    B=item["B"],
                    fit_time=item["fit_time"],
                    X_test=X_test,
                    X_val=X_val,
                    L=L,
                    nodes_df=nodes_df,
                    sensor_budget=0.20,
                    noise_level=0.05,
                    placement=placement,
                    cfg=cfg,
                    rng=np.random.default_rng(cfg.seed + 3000 + trial),
                    trial=trial,
                ))

    df = pd.DataFrame(rows)
    for method, item in bases.items():
        for key, value in item.get("diagnostics", {}).items():
            df.loc[df["method"] == method, key] = value

    raw_path = tables_dir / "raw_results.csv"
    df.to_csv(raw_path, index=False)

    print("[7/7] Saving tables and figures...")
    save_tables_and_figures(
        df=df,
        G=G,
        nodes_df=nodes_df,
        edges_df=edges_df,
        weather=weather,
        tables_dir=tables_dir,
        figures_dir=figures_dir,
    )

    manifest = {
        "config": asdict(cfg),
        "place": cfg.place,
        "bbox": osm_payload["bbox"],
        "centroid": {"lat": centroid_lat, "lon": centroid_lon},
        "n_grid_nodes": int(G.number_of_nodes()),
        "n_grid_edges": int(G.number_of_edges()),
        "n_weather_hours": int(len(weather)),
        "methods": list(bases.keys()),
        "interpretation": [
            "OSM power topology and Open-Meteo weather are real public data.",
            "Node-level response fields are generated by a transparent graph-physics surrogate.",
            "This validates sparse-sensor recovery on real infrastructure topology, not proprietary SCADA measurements.",
        ],
    }
    with open(outdir / "manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print("\nDone.")
    print(f"Grid nodes: {G.number_of_nodes()}, edges: {G.number_of_edges()}")
    print(f"Outputs saved to: {outdir}")


