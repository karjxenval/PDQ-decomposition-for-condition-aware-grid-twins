#!/usr/bin/env python3
"""
Real-grid sparse-sensor validation for condition-aware full-field recovery.

What this script does:
  1. Downloads real power-grid infrastructure from OpenStreetMap using Overpass.
  2. Builds a graph from OSM power lines/cables/minor lines.
  3. Downloads real historical weather from Open-Meteo for the grid centroid.
  4. Generates topology-aware operational response snapshots on the real grid.
  5. Performs sparse-sensor recovery using SVD, randomized SVD, CUR, and PDQ-style bases.
  6. Saves a compact evidence package of CSV tables and figures.

Important interpretation:
  This is public real-grid-topology validation, not proprietary utility SCADA validation.
  The network topology and weather are real public data. The node-level response fields
  are generated by a transparent graph-physics surrogate because public full-field voltage
  or loading measurements are usually unavailable.

Outputs:
  outdir/
    data/
      osm_power_elements.json
      grid_nodes.csv
      grid_edges.csv
      weather_hourly.csv
      snapshots.csv
    tables/
      raw_results.csv
      table_sensor_budget.csv
      table_noise.csv
      table_placement.csv
      summary_key_results.csv
    figures/
      real_grid_map.png
      real_grid_weather.png
      fig_sensor_budget_relerr.png
      fig_noise_relerr.png
      fig_placement_relerr.png
      fig_condition_vs_error.png
    manifest.json

Dependencies:
  numpy, pandas, scipy, matplotlib, requests, networkx
"""

