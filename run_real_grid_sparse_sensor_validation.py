def geocode_place(place: str, cfg: Config) -> Tuple[float, float, float, float, float, float]:
    """
    Returns north, west, south, east, lat, lon.
    """
    params = {
        "q": place,
        "format": "json",
        "limit": 1,
        "polygon_geojson": 0,
    }
    data = http_get_json(cfg.nominatim_url, params=params, user_agent=cfg.user_agent, timeout=60)
    if not data:
        raise RuntimeError(f"Could not geocode place: {place}")

    item = data[0]
    south, north, west, east = [float(v) for v in item["boundingbox"]]
    lat = float(item["lat"])
    lon = float(item["lon"])

    return north, west, south, east, lat, lon


def build_overpass_query(north: float, west: float, south: float, east: float) -> str:
    """
    Download power ways and nodes inside bounding box.
    We include line, minor_line, cable, substation, transformer, tower, pole.
    """
    bbox = f"{south},{west},{north},{east}"
    query = f"""
    [out:json][timeout:120];
    (
      way["power"~"^(line|minor_line|cable)$"]({bbox});
      node["power"~"^(substation|transformer|tower|pole)$"]({bbox});
      way["power"="substation"]({bbox});
      relation["power"="substation"]({bbox});
    );
    (._;>;);
    out body;
    """
    return query


def download_osm_power(cfg: Config, out_json: Path) -> Dict[str, Any]:
    if cfg.bbox is not None:
        north, west, south, east = cfg.bbox
        lat = 0.5 * (north + south)
        lon = 0.5 * (west + east)
    else:
        north, west, south, east, lat, lon = geocode_place(cfg.place, cfg)

    query = build_overpass_query(north, west, south, east)
    data = http_post_text(cfg.overpass_url, query, user_agent=cfg.user_agent, timeout=180)

    payload = {
        "place": cfg.place,
        "bbox": {"north": north, "west": west, "south": south, "east": east},
        "centroid": {"lat": lat, "lon": lon},
        "overpass_query": query,
        "osm_data": data,
    }

    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(payload, f)

    return payload


