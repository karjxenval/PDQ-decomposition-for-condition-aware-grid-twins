def parse_osm_power_graph(payload: Dict[str, Any], cfg: Config) -> Tuple[nx.Graph, pd.DataFrame, pd.DataFrame]:
    elements = payload["osm_data"].get("elements", [])

    osm_nodes: Dict[int, Tuple[float, float, Dict[str, Any]]] = {}
    ways: List[Dict[str, Any]] = []

    for el in elements:
        if el.get("type") == "node" and "lat" in el and "lon" in el:
            osm_nodes[int(el["id"])] = (
                float(el["lat"]),
                float(el["lon"]),
                el.get("tags", {}),
            )
        elif el.get("type") == "way" and "nodes" in el:
            tags = el.get("tags", {})
            if tags.get("power") in {"line", "minor_line", "cable", "substation"}:
                ways.append(el)

    G = nx.Graph()

    # Add all nodes referenced by line/cable ways.
    for way in ways:
        ptype = way.get("tags", {}).get("power", "")
        if ptype not in {"line", "minor_line", "cable"}:
            continue
        node_ids = [int(v) for v in way.get("nodes", []) if int(v) in osm_nodes]
        for nid in node_ids:
            lat, lon, tags = osm_nodes[nid]
            G.add_node(nid, lat=lat, lon=lon, tags=tags, power=tags.get("power", ""))
        for a, b in zip(node_ids[:-1], node_ids[1:]):
            if a == b:
                continue
            lat1, lon1, _ = osm_nodes[a]
            lat2, lon2, _ = osm_nodes[b]
            length_km = haversine_km(lat1, lon1, lat2, lon2)
            if length_km <= 0:
                continue
            voltage = way.get("tags", {}).get("voltage", "")
            G.add_edge(
                a,
                b,
                length_km=length_km,
                power=ptype,
                voltage=voltage,
                osm_way_id=way.get("id"),
            )

    if G.number_of_nodes() == 0 or G.number_of_edges() == 0:
        raise RuntimeError(
            "No usable OSM power-line graph was found. Try a larger bbox or a different place."
        )

    # Keep largest connected component.
    components = sorted(nx.connected_components(G), key=len, reverse=True)
    G = G.subgraph(components[0]).copy()

    # Limit size for quick reproducible experiments.
    if G.number_of_nodes() > cfg.max_nodes:
        # Keep high-degree/geographically central component subset by BFS from max-degree node.
        degrees = dict(G.degree())
        start = max(degrees, key=degrees.get)
        chosen = []
        seen = {start}
        queue = [start]
        while queue and len(chosen) < cfg.max_nodes:
            u = queue.pop(0)
            chosen.append(u)
            neigh = sorted(G.neighbors(u), key=lambda v: degrees.get(v, 0), reverse=True)
            for v in neigh:
                if v not in seen:
                    seen.add(v)
                    queue.append(v)
        G = G.subgraph(chosen).copy()

    if G.number_of_nodes() < cfg.min_nodes_required:
        raise RuntimeError(
            f"Only {G.number_of_nodes()} grid nodes found. Need at least {cfg.min_nodes_required}. "
            "Try a larger bbox or another city/region."
        )

    # Relabel nodes to compact integer ids.
    mapping = {old: i for i, old in enumerate(G.nodes())}
    old_ids = {i: old for old, i in mapping.items()}
    G2 = nx.relabel_nodes(G, mapping, copy=True)
    nx.set_node_attributes(G2, old_ids, "osm_id")

    node_rows = []
    for i, data in G2.nodes(data=True):
        node_rows.append({
            "node": i,
            "osm_id": data.get("osm_id"),
            "lat": data.get("lat"),
            "lon": data.get("lon"),
            "power": data.get("power", ""),
            "degree": int(G2.degree(i)),
        })
    nodes_df = pd.DataFrame(node_rows).sort_values("node")

    edge_rows = []
    for u, v, data in G2.edges(data=True):
        edge_rows.append({
            "u": int(u),
            "v": int(v),
            "length_km": float(data.get("length_km", np.nan)),
            "power": data.get("power", ""),
            "voltage": data.get("voltage", ""),
            "osm_way_id": data.get("osm_way_id", ""),
        })
    edges_df = pd.DataFrame(edge_rows)

    return G2, nodes_df, edges_df


def graph_laplacian_conductance(G: nx.Graph) -> csr_matrix:
    n = G.number_of_nodes()
    rows, cols, data = [], [], []

    conductance = {}
    for u, v, d in G.edges(data=True):
        length = max(float(d.get("length_km", 1.0)), 1e-3)
        c = 1.0 / length
        conductance[(u, v)] = c
        conductance[(v, u)] = c

    diag = np.zeros(n)
    for u, v in G.edges():
        c = conductance[(u, v)]
        diag[u] += c
        diag[v] += c
        rows.extend([u, v])
        cols.extend([v, u])
        data.extend([-c, -c])

    rows.extend(range(n))
    cols.extend(range(n))
    data.extend(diag)

    L = csr_matrix((data, (rows, cols)), shape=(n, n))
    return L


